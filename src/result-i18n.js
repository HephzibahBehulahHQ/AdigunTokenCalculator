// Plain text only: render the returned string with textContent. Substitutions are
// single-pass and do not interpret replacement tokens or inherited properties.
export function resultText(locale,key,values={}){
  const copy=Object.hasOwn(RESULT_COPY,locale)?RESULT_COPY[locale]:RESULT_COPY.en;
  const template=Object.hasOwn(copy,key)?copy[key]:Object.hasOwn(RESULT_COPY.en,key)?RESULT_COPY.en[key]:String(key);
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g,(placeholder,name)=>
    values!=null&&Object.hasOwn(values,name)?String(values[name]):placeholder);
}
